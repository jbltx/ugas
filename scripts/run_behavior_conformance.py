#!/usr/bin/env python3
"""Validate and execute the portable behavior corpus, or verify an adapter's observations.

Run from the repository root. --corpus accepts a packaged corpus. --results accepts
{fixture_id: [observation_after_each_step, ...]} from a downstream adapter instead of
running the reference models. Checked-in expectations are never generated by this runner.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import json
import math
from pathlib import Path
import sys

from jsonschema import Draft7Validator
from behavior_model import MODELS

ROOT = Path(__file__).resolve().parent.parent
REFERENCE_MODE = object()  # JSON null must never select reference execution.


def load(path):
    def reject_constant(value):
        raise ValueError(f"non-finite JSON number: {value}")
    def finite_float(value):
        number = float(value)
        if not math.isfinite(number):
            raise ValueError(f"non-finite JSON number: {value}")
        return number
    return json.loads(path.read_text(encoding="utf-8"), parse_constant=reject_constant,
                      parse_float=finite_float)


def json_equal(actual, expected):
    """Compare JSON values without treating booleans as numbers.

    JSON numbers such as 1 and 1.0 are equivalent, and object key order is irrelevant.
    Container contents keep the same type distinctions recursively.
    """
    if type(expected) in (int, float):
        return type(actual) in (int, float) and actual == expected
    if type(actual) is not type(expected):
        return False
    if isinstance(expected, list):
        return len(actual) == len(expected) and all(json_equal(a, e) for a, e in zip(actual, expected))
    if isinstance(expected, dict):
        return actual.keys() == expected.keys() and all(json_equal(actual[key], value) for key, value in expected.items())
    return actual == expected


def normalize_input_numbers(value):
    """Use Python integers for integer-valued JSON inputs, including nested IDs.

    Draft-07 accepts 1, 1.0 and 1e0 as integers. Model indexing, bitwise operations
    and identity formatting must not depend on their JSON spelling. Fractional
    numbers and nonnumeric values (especially booleans) retain their types.
    """
    if type(value) is float and value.is_integer():
        return int(value)
    if isinstance(value, list):
        return [normalize_input_numbers(item) for item in value]
    if isinstance(value, dict):
        return {key: normalize_input_numbers(item) for key, item in value.items()}
    return value


def run_case(case, external=REFERENCE_MODE):
    if external is not REFERENCE_MODE:
        if not isinstance(external, list):
            raise ValueError("adapter observations must be a list")
        if len(external) != len(case["steps"]):
            raise ValueError("observation count differs from step count")
    model = None
    if external is REFERENCE_MODE:
        model = MODELS[case["model"]](**normalize_input_numbers(case.get("initial", {})))
    observations = []
    for i, step in enumerate(case["steps"]):
        error = None
        if external is REFERENCE_MODE:
            try:
                method = getattr(model, step["op"])
                method(**normalize_input_numbers(step.get("args", {})))
            except ValueError as exc:
                error = str(exc)
            observation = deepcopy(model.observe())
            observation["error"] = error
        else:
            observation = external[i]
            if not isinstance(observation, dict):
                raise ValueError(f"step {i + 1}: expected an observation object")
        expected = {"error": step.get("error"), **step.get("expect", {})}
        for key, value in expected.items():
            if key not in observation or not json_equal(observation[key], value):
                raise ValueError(f"step {i + 1} ({step['op']}), {key}: expected {value!r}, got {observation.get(key)!r}")
        observations.append(observation)
    return observations


def run(corpus, results=REFERENCE_MODE):
    if results is not REFERENCE_MODE and not isinstance(results, dict):
        raise ValueError("adapter results must be an object keyed by fixture ID")
    schema = load(corpus / "format.schema.json")
    Draft7Validator.check_schema(schema)
    validator = Draft7Validator(schema)
    paths = sorted(corpus.glob("*.json"))
    seen = set()
    observations = {}
    for path in paths:
        if path.name == "format.schema.json":
            continue
        case = load(path)
        validator.validate(case)
        if case["id"] in seen:
            raise ValueError(f"duplicate fixture id: {case['id']}")
        seen.add(case["id"])
        if not any(step.get("expect") for step in case["steps"]):
            raise ValueError(f"{path.name}: missing behavioral assertions")
        if results is not REFERENCE_MODE and case["id"] not in results:
            raise ValueError(f"missing adapter result: {case['id']}")
        try:
            observations[case["id"]] = run_case(case, REFERENCE_MODE if results is REFERENCE_MODE else results[case["id"]])
        except (ValueError, TypeError, AttributeError) as exc:
            raise ValueError(f"{path.name}: {exc}") from exc
    if not seen:
        raise ValueError("empty behavior corpus")
    if results is not REFERENCE_MODE and set(results) != seen:
        raise ValueError("adapter result IDs differ from the corpus")
    return observations


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, default=ROOT / "conformance/behavior")
    parser.add_argument("--results", type=Path, help="verify externally produced observations")
    args = parser.parse_args()
    try:
        results = load(args.results) if args.results else REFERENCE_MODE
        observations = run(args.corpus, results)
    except Exception as exc:
        print(f"Behavior conformance failed: {exc}", file=sys.stderr)
        return 1
    print(f"Behavior conformance OK ({len(observations)} scenarios, {sum(map(len, observations.values()))} steps)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
